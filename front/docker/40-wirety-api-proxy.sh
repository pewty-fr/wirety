#!/bin/sh
# Proxies /api to the Wirety server when the front is the only public entry
# point (e.g. Scaleway Serverless Containers with a private server container):
#
#   API_PROXY_ENABLED     "true" to proxy /api (default "false": /api is left
#                         to an ingress, as with the Helm chart)
#   API_PROXY_URL         the server, scheme://host[:port] without a path,
#                         e.g. https://wirety-server-abc.functions.fnc.fr-par.scw.cloud
#   API_PROXY_AUTH_TOKEN  optional, sent as the X-Auth-Token header of every
#                         proxied request (a private Scaleway container's token);
#                         a X-Auth-Token sent by the browser is never forwarded
#
# Run by the nginx image's entrypoint before nginx starts; a wrong setting
# stops the container with an explanation.
set -eu

conf=/etc/nginx/wirety.d/api-proxy.conf

fail() {
    echo "$0: $*" >&2
    exit 1
}

case "$(printf '%s' "${API_PROXY_ENABLED:-false}" | tr '[:upper:]' '[:lower:]')" in
    true | 1 | yes | on) ;;
    false | 0 | no | off | "") exit 0 ;;
    *) fail "API_PROXY_ENABLED must be true or false, not \"${API_PROXY_ENABLED}\"" ;;
esac

url=${API_PROXY_URL:-}
url=${url%/}
case "$url" in
    http://* | https://*) ;;
    "") fail "API_PROXY_ENABLED is true: set API_PROXY_URL to the Wirety server (scheme://host[:port])" ;;
    *) fail "API_PROXY_URL must start with http:// or https://, not \"$url\"" ;;
esac
hostport=${url#*://}
case "$hostport" in
    "" | */* | *[!A-Za-z0-9.:-]*) fail "API_PROXY_URL must be scheme://host[:port] without a path, not \"$url\"" ;;
esac
host=${hostport%%:*}

token=${API_PROXY_AUTH_TOKEN:-}
case "$token" in
    *[!A-Za-z0-9._~+/=-]*) fail "API_PROXY_AUTH_TOKEN has characters a token does not have" ;;
esac

# A name with a dot (a cloud endpoint) is resolved at request time, so the
# proxy follows its address changes; nginx does not use the search domains,
# so a short name (a Docker Compose or Kubernetes service) is resolved once,
# at startup, by the system resolver.
nameserver=$(awk '$1 == "nameserver" { print $2; exit }' /etc/resolv.conf 2>/dev/null || true)
case "$nameserver" in
    *:*) nameserver="[$nameserver]" ;;
esac
dynamic=false
case "$host" in
    *[!0-9.]*.*) if [ -n "$nameserver" ]; then dynamic=true; fi ;;
esac

{
    echo "# Generated by $0 at startup."
    echo "location /api/ {"
    if [ "$dynamic" = true ]; then
        echo "    resolver $nameserver valid=30s ipv6=off;"
        echo "    set \$wirety_api_upstream \"$url\";"
        echo "    proxy_pass \$wirety_api_upstream;"
    else
        echo "    proxy_pass $url;"
    fi
    echo "    proxy_http_version 1.1;"
    echo "    proxy_set_header Upgrade \$http_upgrade;"
    echo "    proxy_set_header Connection \$wirety_connection_upgrade;"
    echo "    proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;"
    echo "    proxy_set_header X-Forwarded-Proto \$wirety_forwarded_proto;"
    echo "    proxy_set_header X-Forwarded-Host \$host;"
    # Set (to the token or to nothing): the browser's own value never passes.
    echo "    proxy_set_header X-Auth-Token \"$token\";"
    if [ "${url%%://*}" = https ]; then
        echo "    proxy_ssl_server_name on;"
        echo "    proxy_ssl_verify on;"
        echo "    proxy_ssl_trusted_certificate /etc/ssl/certs/ca-certificates.crt;"
        echo "    proxy_ssl_verify_depth 4;"
    fi
    # Agents keep a WebSocket open; the MCP endpoint streams (SSE).
    echo "    proxy_read_timeout 1h;"
    echo "    proxy_send_timeout 1h;"
    echo "    proxy_buffering off;"
    echo "    client_max_body_size 10m;"
    echo "}"
} > "$conf"

echo "$0: proxying /api to $url$([ -n "$token" ] && echo ' with an X-Auth-Token')"
